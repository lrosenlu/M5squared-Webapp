#!/usr/bin/env python3
"""
Generate JS constants and known-answer test vectors from the upstream m5squared Python code.

  python3 tools/gen_web_vectors.py /path/to/6static/m5squared

Writes src/generated.js (CRC table, QR charset) and test/vectors.json. Requires pycryptodome.
"""
import json
import sys
from pathlib import Path

if len(sys.argv) != 2:
    sys.exit(__doc__)
sys.path.insert(0, str(Path(sys.argv[1]).resolve()))

import m25_crypto  # noqa: E402
from m25_crypto import M25Encryptor, M25Decryptor  # noqa: E402
from m25_ecs import ECSPacketBuilder  # noqa: E402
from m25_protocol import CRC_TABLE, add_delimiters, calculate_crc  # noqa: E402
from m25_qr_to_key import M25QRConverter  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
hx = lambda b: b.hex()  # noqa: E731

(ROOT / "src" / "generated.js").write_text(
    "// AUTO-GENERATED by tools/gen_web_vectors.py from the upstream Python sources. Do not edit.\n"
    f"export const CRC_TABLE = new Uint16Array({json.dumps(list(CRC_TABLE))});\n"
    f"export const QR_CHARSET = {json.dumps(''.join(M25QRConverter.UPK_CHARSET))};\n"
)

fresh = ECSPacketBuilder
builders = {
    "systemModeConnect": lambda b: b.build_write_system_mode(1),
    "readSOC": lambda b: b.build_read_soc(),
    "readAssistLevel": lambda b: b.build_read_assist_level(),
    "readDriveMode": lambda b: b.build_read_drive_mode(),
    "readDriveProfile": lambda b: b.build_read_drive_profile(),
    "readDriveProfileParams1": lambda b: b.build_read_drive_profile_params(1),
    "readCruiseValues": lambda b: b.build_read_cruise_values(),
    "readDuoDriveParams": lambda b: b.build_read_duo_drive_params(),
    "readSWVersion": lambda b: b.build_read_sw_version(),
    "writeAssistLevel1": lambda b: b.build_write_assist_level(1),
    "writeDriveModeAutoHold": lambda b: b.build_write_drive_mode(0x01),
    "writeDriveModeRemoteCruise": lambda b: b.build_write_drive_mode(0x06),
    "writeDriveProfile2": lambda b: b.build_write_drive_profile(2),
    "writeRemoteSpeedNeg80": lambda b: b.build_write_remote_speed(-80),
    "writeRemoteSpeed150": lambda b: b.build_write_remote_speed(150),
    "writeDriveProfileParams": lambda b: b.build_write_drive_profile_params(1, 80, 1667, 300, 30, 50, 20, 42, 28),
}

key = bytes(range(16))
spps = [fresh().build_read_soc(), fresh().build_write_remote_speed(-80),
        fresh().build_write_drive_profile_params(1, 80, 1667, 300, 30, 50, 20, 42, 28)]
encryption = []
for iv in (bytes(range(0xA0, 0xB0)), bytes([0xEF] * 16)):
    m25_crypto.get_random_bytes = lambda n, iv=iv: iv
    enc, dec = M25Encryptor(key), M25Decryptor(key)
    for spp in spps:
        pkt = enc.encrypt(spp)
        assert dec.decrypt(pkt) == spp
        encryption.append({"iv": hx(iv), "spp": hx(spp), "packet": hx(pkt)})

wrong = M25Decryptor(bytes([7]) * 16)
m25_crypto.get_random_bytes = lambda n: bytes(range(0xA0, 0xB0))
good = M25Encryptor(key).encrypt(spps[0])
assert wrong.decrypt(good) is None

cs = M25QRConverter.UPK_CHARSET
conv = M25QRConverter()
qrs = ["ABCDEFGHJKLMNPQRSTUVWX",
       "".join(cs[(i * 7) % 64] for i in range(22)),
       "".join(cs[63 - (i * 3) % 64] for i in range(22))]

crc_inputs = [bytes(range(40)), bytes([0xEF, 1, 0xEF, 0xEF, 2]), b"Alber_M25_emotio"]
stuff = [bytes([0xEF, 1, 2]), bytes([0xEF, 0xEF, 1, 0xEF, 2, 0xEF]), bytes([0xEF, 0, 0xEF, 0xEF, 0xEF])]

(ROOT / "test" / "vectors.json").write_text(json.dumps({
    "key": hx(key),
    "crc": [{"data": hx(d), "crc": calculate_crc(d, len(d))} for d in crc_inputs],
    "stuffing": [{"raw": hx(d), "stuffed": hx(add_delimiters(d))} for d in stuff],
    "packets": {n: hx(f(fresh())) for n, f in builders.items()},
    "encryption": encryption,
    "wrongKeyPacket": hx(good),
    "qr": [{"qr": q, "key": hx(conv.convert_qr_to_key(q))} for q in qrs],
}, indent=1))
print("ok")
